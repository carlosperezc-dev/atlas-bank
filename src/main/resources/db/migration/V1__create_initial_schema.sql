
-- =====================================================
-- V1 - Initial database schema
-- Atlas Bank
-- =====================================================

-- =====================================================
-- CUSTOMERS
-- =====================================================

CREATE TABLE customers (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           name VARCHAR(255) NOT NULL,
                           email VARCHAR(255) NOT NULL,
                           status VARCHAR(20) NOT NULL,
                           keycloak_subject VARCHAR(255),
                           created_at TIMESTAMP NOT NULL,

                           CONSTRAINT uk_customers_email UNIQUE (email),
                           CONSTRAINT uk_customers_keycloak_subject UNIQUE (keycloak_subject),

                           CONSTRAINT chk_customers_status
                               CHECK (status IN ('ACTIVE', 'SUSPENDED', 'CLOSED'))
);

-- =====================================================
-- ACCOUNTS
-- =====================================================

CREATE TABLE accounts (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          account_number VARCHAR(255) NOT NULL,
                          owner_name VARCHAR(255) NOT NULL,
                          email VARCHAR(255) NOT NULL,
                          type VARCHAR(20) NOT NULL,
                          balance NUMERIC(19, 2) NOT NULL,
                          currency VARCHAR(3) NOT NULL,
                          status VARCHAR(20) NOT NULL,
                          created_at TIMESTAMP NOT NULL,
                          customer_id BIGINT,

                          CONSTRAINT uk_accounts_account_number UNIQUE (account_number),

                          CONSTRAINT fk_accounts_customer
                              FOREIGN KEY (customer_id)
                                  REFERENCES customers(id),

                          CONSTRAINT chk_accounts_type
                              CHECK (type IN ('SAVINGS', 'CHECKING', 'PREMIUM')),

                          CONSTRAINT chk_accounts_status
                              CHECK (status IN ('ACTIVE', 'FROZEN', 'CLOSED')),

                          CONSTRAINT chk_accounts_currency
                              CHECK (currency IN ('EUR', 'USD'))
);

-- =====================================================
-- TRANSACTIONS
-- =====================================================

CREATE TABLE transactions (
                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              type VARCHAR(20) NOT NULL,
                              source_account_id BIGINT,
                              target_account_id BIGINT,
                              amount NUMERIC(19, 2) NOT NULL,
                              fee NUMERIC(19, 2) NOT NULL,
                              status VARCHAR(20) NOT NULL,
                              created_at TIMESTAMP NOT NULL,

                              CONSTRAINT fk_transactions_source_account
                                  FOREIGN KEY (source_account_id)
                                      REFERENCES accounts(id),

                              CONSTRAINT fk_transactions_target_account
                                  FOREIGN KEY (target_account_id)
                                      REFERENCES accounts(id),

                              CONSTRAINT chk_transactions_type
                                  CHECK (type IN ('DEPOSIT', 'WITHDRAWAL', 'TRANSFER')),

                              CONSTRAINT chk_transactions_status
                                  CHECK (status IN ('PENDING', 'VALIDATED', 'EXECUTED', 'REJECTED', 'REVERSED'))
);

-- =====================================================
-- INDEXES
-- =====================================================

CREATE INDEX idx_accounts_customer_id
    ON accounts(customer_id);

CREATE INDEX idx_transactions_source_account_id
    ON transactions(source_account_id);

CREATE INDEX idx_transactions_target_account_id
    ON transactions(target_account_id);

CREATE INDEX idx_transactions_created_at
    ON transactions(created_at);
